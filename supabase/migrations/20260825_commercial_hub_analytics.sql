create table if not exists public.presentations (
  id uuid primary key default gen_random_uuid(),
  salesperson_id uuid not null references public.salespeople(id),
  title text not null default 'Apresentação Institucional ViaGate',
  status text not null default 'draft' check (status in ('draft', 'published', 'expired')),
  current_version integer not null default 0 check (current_version >= 0),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.presentation_versions (
  id uuid primary key default gen_random_uuid(),
  presentation_id uuid not null references public.presentations(id) on delete cascade,
  version_number integer not null check (version_number > 0),
  public_token uuid not null unique default gen_random_uuid(),
  content jsonb not null default '{}'::jsonb,
  published_at timestamptz,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  unique (presentation_id, version_number)
);

create table if not exists public.shared_document_events (
  id bigint generated by default as identity primary key,
  document_kind text not null check (document_kind in ('presentation', 'proposal')),
  presentation_version_id uuid references public.presentation_versions(id) on delete cascade,
  proposal_version_id uuid references public.proposal_versions(id) on delete cascade,
  session_id uuid not null,
  event_type text not null check (event_type in ('open', 'start', 'slide_view', 'complete')),
  slide_number integer,
  slide_total integer,
  created_at timestamptz not null default now(),
  check (
    (document_kind = 'presentation' and presentation_version_id is not null and proposal_version_id is null)
    or
    (document_kind = 'proposal' and proposal_version_id is not null and presentation_version_id is null)
  ),
  check (slide_number is null or slide_number > 0),
  check (slide_total is null or slide_total > 0)
);

create index if not exists presentations_created_by_idx on public.presentations(created_by, updated_at desc);
create index if not exists presentation_versions_presentation_id_idx on public.presentation_versions(presentation_id, version_number desc);
create index if not exists shared_document_events_presentation_idx on public.shared_document_events(presentation_version_id, created_at desc);
create index if not exists shared_document_events_proposal_idx on public.shared_document_events(proposal_version_id, created_at desc);

create unique index if not exists shared_document_events_dedupe_idx
on public.shared_document_events (
  document_kind,
  coalesce(presentation_version_id, proposal_version_id),
  session_id,
  event_type,
  coalesce(slide_number, 0)
);

